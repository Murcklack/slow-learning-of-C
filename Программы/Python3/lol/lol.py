import math
import time

# Настройки формулы
C = 30       # Центр спирали (отступ слева)
A = 15       # Амплитуда (радиус)
F = 0.3      # Частота закручивания по вертикали
speed = 0.1  # Скорость вращения во времени (шаг для t)

t = 0.0      # Стартовое время

while True:
    # Очистка экрана (для Windows используйте 'cls', для Linux/Mac 'clear')
    # Здесь используется ANSI-код возврата курсора в начало для плавности
    print("\033[H\033[J", end="")
    
    # Цикл построения кадра (20 строк)
    for y in range(20):
        # 1. Формулы
        x1 = round(C + A * math.sin(F * y + t))
        x2 = round(C - A * math.sin(F * y + t))
        
        # 2. Определение левой и правой точки
        L = min(x1, x2)
        R = max(x1, x2)
        
        # 3. Вывод пробелов до первой точки
        print(" " * L, end="")
        
        # 4. Вывод самих точек
        distance = R - L
        if distance == 0:
            # Точки пересеклись
            print("x")
        else:
            # Точка 1, затем пробелы между ними, затем Точка 2
            spaces_between = distance - 1
            print("O" + (" " * spaces_between) + "O")
            
    # Увеличиваем время (поворачиваем спираль для следующего кадра)
    t += speed
    
    # Пауза, чтобы анимация не мельтешила
    time.sleep(0.05)
