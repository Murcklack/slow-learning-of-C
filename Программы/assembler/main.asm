section .data                                ; Начало секции инициализированных данных
    msg db 'Hello, World!', 0xA              ; Объявление метки msg, выделение байтов (db) под строку и символ переноса (0xA)
    len equ $ - msg                          ; Вычисление длины: текущий адрес памяти ($) минус начальный адрес (msg)

section .text                                ; Начало секции исполняемого кода
    global _start                            ; Экспорт метки _start для компоновщика (точка входа в программу)

_start:                                      ; Метка начала выполнения программы
    ; Вывод текста на экран
    mov rax, 1                               ; Помещаем в регистр rax номер системного вызова sys_write (1)
    mov rdi, 1                               ; Помещаем в rdi файловый дескриптор 1 (стандартный вывод - stdout)
    mov rsi, msg                             ; Помещаем в rsi указатель на начальный адрес нашей строки
    mov rdx, len                             ; Помещаем в rdx длину выводимой строки в байтах
    syscall                                  ; Передаем управление ядру Linux для выполнения sys_write

    ; Корректное завершение программы
    mov rax, 60                              ; Помещаем в rax номер системного вызова sys_exit (60)
    mov rdi, 0                               ; Помещаем в rdi код возврата 0 (успешное завершение)
    syscall                                  ; Передаем управление ядру Linux для выполнения sys_exit